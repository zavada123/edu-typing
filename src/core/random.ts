/** Seeded random numbers (mulberry32): the same seed gives the same exercise, so tests are stable. */
export type Random = () => number

export const seededRandom = (seed: number): Random => {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

export const pick = <T>(items: readonly T[], random: Random): T | undefined => items[Math.floor(random() * items.length)]

export const shuffle = <T>(items: readonly T[], random: Random): T[] => {
  const out = [...items]
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1))
    const a = out[i]
    const b = out[j]
    if (a === undefined || b === undefined) continue
    out[i] = b
    out[j] = a
  }
  return out
}
